// The till receipt printed when the kitchen accepts an order. Pure: the
// receipt is built from the order, then rendered as an 80 mm page that any
// receipt printer set up on the till can print (lib/printer.js sends it).
import { BRAND } from "./brand";
import { formatPrice } from "./cart";
import { formatOrderNumber } from "./orders";

const TIME_ZONE = "Europe/London";

const formatTime = (at) =>
  new Intl.DateTimeFormat("en-GB", { timeZone: TIME_ZONE, hour: "2-digit", minute: "2-digit" }).format(at);
const formatDate = (at) =>
  new Intl.DateTimeFormat("en-GB", { timeZone: TIME_ZONE, day: "2-digit", month: "short", year: "numeric" }).format(at);

function paymentLabel(order) {
  if (order.payment?.status === "paid") return "PAID";
  return order.mode === "delivery" ? "CASH ON DELIVERY" : "TO PAY AT PICKUP";
}

/**
 * What goes on the receipt, in print order. `printedAt` is when it comes out
 * of the till, which is when the order was accepted.
 */
export function buildReceipt(order, printedAt) {
  const isDelivery = order.mode === "delivery";
  const { subtotalPence, discountPence, deliveryPence, totalPence } = order.totals;
  const address = isDelivery && order.address
    ? [order.address.line1, order.address.line2, order.address.postcode].filter(Boolean).join(", ")
    : null;

  return {
    shop: { name: BRAND.name, address: BRAND.address.short, phone: BRAND.phone.label },
    number: formatOrderNumber(order.number),
    mode: isDelivery ? "DELIVERY" : "COLLECTION",
    placed: `${formatDate(order.createdAt)} ${formatTime(order.createdAt)}`,
    printed: formatTime(printedAt),
    customer: { name: order.customer.name, phone: order.customer.phone || null, address },
    lines: order.lines.map((line) => ({
      key: line.key,
      qty: line.qty,
      name: line.name,
      choices: line.choices.map((c) => c.choice),
      price: formatPrice(line.qty * line.unitPence),
    })),
    note: order.note || null,
    totals: [
      ["Subtotal", formatPrice(subtotalPence)],
      ...(discountPence > 0 ? [[order.promo?.title ? `Offer: ${order.promo.title}` : "Offer", `−${formatPrice(discountPence)}`]] : []),
      ...(isDelivery ? [["Delivery", formatPrice(deliveryPence)]] : []),
    ],
    total: formatPrice(totalPence),
    payment: paymentLabel(order),
  };
}

const ESCAPES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
// Customer names, notes and addresses are typed by customers: always escaped.
export const escapeHtml = (value) => String(value ?? "").replace(/[&<>"']/g, (ch) => ESCAPES[ch]);

const row = (left, right, cls = "") =>
  `<div class="row ${cls}"><span>${escapeHtml(left)}</span><span>${escapeHtml(right)}</span></div>`;

// Thermal paper is black on white, so plain text, bold and rules only; the
// logo is left off rather than printed as an approximation.
const RECEIPT_CSS = `
@page { size: 80mm auto; margin: 0; }
* { box-sizing: border-box; margin: 0; padding: 0; }
body { width: 72mm; margin: 0 auto; padding: 3mm 0 6mm; font: 12px/1.35 "Courier New", ui-monospace, monospace; color: #000; background: #fff; }
.c { text-align: center; }
.shop { font-size: 17px; font-weight: 700; text-transform: uppercase; }
.num { font-size: 30px; font-weight: 700; letter-spacing: 1px; margin-top: 2mm; }
.mode { display: inline-block; border: 2px solid #000; padding: 0 2mm; font-size: 15px; font-weight: 700; margin: 1mm 0; }
hr { border: 0; border-top: 1px dashed #000; margin: 2mm 0; }
.row { display: flex; justify-content: space-between; gap: 2mm; }
.row span:last-child { white-space: nowrap; }
.item { font-size: 13px; font-weight: 700; }
.choice { padding-left: 5mm; }
.note { border: 1px solid #000; padding: 1mm 1.5mm; margin-top: 1mm; }
.total { font-size: 16px; font-weight: 700; }
.pay { font-weight: 700; margin-top: 1mm; }
.stamp { text-align: center; }
.stamp svg { display: block; width: 36mm; height: 36mm; margin: 1.5mm auto; }
.stamp-head { font-size: 14px; font-weight: 700; }
`;

// `qrSvg` is generated by the qrcode library from our own URL, never from
// anything a customer typed, so it goes in as markup.
const stampBlock = (qrSvg) =>
  qrSvg
    ? `<hr><div class="stamp"><div class="stamp-head">SCAN FOR YOUR FLEX STAMP</div>${qrSvg}<div>One stamp per receipt, within 14 days</div></div>`
    : "";

/**
 * The receipt as a complete HTML page sized for 80 mm till paper.
 * `qrSvg`: the receipt's one-time stamp QR, as SVG markup.
 */
export function receiptHtml(receipt, { qrSvg = null } = {}) {
  const { shop, customer } = receipt;
  const lines = receipt.lines
    .map(
      (line) =>
        row(`${line.qty} x ${line.name}`, line.price, "item") +
        line.choices.map((choice) => `<div class="choice">- ${escapeHtml(choice)}</div>`).join("")
    )
    .join("");

  return `<!doctype html><html lang="en-GB"><head><meta charset="utf-8"><title>Receipt ${escapeHtml(receipt.number)}</title><style>${RECEIPT_CSS}</style></head><body>
<div class="c"><div class="shop">${escapeHtml(shop.name)}</div><div>${escapeHtml(shop.address)}</div><div>${escapeHtml(shop.phone)}</div></div>
<hr>
<div class="c"><div class="num">${escapeHtml(receipt.number)}</div><div class="mode">${escapeHtml(receipt.mode)}</div></div>
${row("Placed", receipt.placed)}${row("Accepted", receipt.printed)}
<hr>
<div class="item">${escapeHtml(customer.name)}</div>
${customer.phone ? `<div>${escapeHtml(customer.phone)}</div>` : ""}
${customer.address ? `<div>${escapeHtml(customer.address)}</div>` : ""}
<hr>
${lines}
${receipt.note ? `<div class="note">NOTE: ${escapeHtml(receipt.note)}</div>` : ""}
<hr>
${receipt.totals.map(([label, value]) => row(label, value)).join("")}
${row("TOTAL", receipt.total, "total")}
<div class="c pay">${escapeHtml(receipt.payment)}</div>
${stampBlock(qrSvg)}
<hr>
<div class="c">Thank you for ordering with ${escapeHtml(shop.name)}</div>
</body></html>`;
}
